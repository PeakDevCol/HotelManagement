/**
 * The same tokens for the Material components the app still uses (date picker, menus, dialogs),
 * so they look like the rest. Elevation does not tint surfaces: depth comes from the tokens.
 */
internal fun MajesticColors.toMaterialColorScheme(): ColorScheme {
    val base = if (isDark) darkColorScheme() else lightColorScheme()
    return base.copy(
        primary = primary,
        onPrimary = onPrimary,
        primaryContainer = primarySoft,
        onPrimaryContainer = onPrimarySoft,
        inversePrimary = inversePrimary,
        secondary = primary,
        onSecondary = onPrimary,
        secondaryContainer = primarySoft,
        onSecondaryContainer = onPrimarySoft,
        tertiary = brandRaised,
        onTertiary = onBrand,
        tertiaryContainer = primarySoft,
        onTertiaryContainer = onPrimarySoft,
        background = surface,
        onBackground = ink,
        surface = surface,
        onSurface = ink,
        surfaceVariant = surfaceSunken,
        onSurfaceVariant = inkMuted,
        surfaceTint = Color.Transparent,
        inverseSurface = inverseSurface,
        inverseOnSurface = onInverseSurface,
        error = danger,
        onError = onDanger,
        errorContainer = dangerSoft,
        onErrorContainer = danger,
        outline = lineStrong,
        outlineVariant = line,
        scrim = scrim,
        surfaceBright = surfaceRaised,
        surfaceDim = surfaceSunken,
        surfaceContainerLowest = surfaceRaised,
        surfaceContainerLow = surfaceRaised,
        surfaceContainer = surfaceRaised,
        surfaceContainerHigh = surfaceRaised,
        surfaceContainerHighest = surfaceSunken,
    )
}
